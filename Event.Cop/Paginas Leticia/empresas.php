            <h2>Perguntas frequentes</h2>


            <details class="pergunta">

                <summary>
                    O que é e EventCop?
                    <span>⌄</span>
                </summary>

                <p>
                  A EventCop é uma plataforma especializada na organização e gestão de workshops e eventos corporativos. Ela centraliza inscrições, programação e informações em um só lugar, facilitando o planejamento e o gerenciamento dos eventos.
                </p>

            </details>


            <details class="pergunta">

                <summary>
                    Só posso usar o EventCop se eu tiver um CNPJ?
                    <span>⌄</span>
                </summary>

                <p>
                   Não. A EventCop pode ser utilizada tanto por empresas quanto por profissionais responsáveis pela organização de eventos corporativos. O CNPJ pode ser solicitado apenas em recursos específicos da plataforma.
                </p>

            </details>


            <details class="pergunta">

                <summary>
                    Posso criar eventos apenas para meus colaboradores?
                    <span>⌄</span>
                </summary>

                <p>
                   Sim. Você pode criar eventos restritos para colaboradores ou convidados específicos, controlando quem terá acesso às informações e inscrições.
                </p>

            </details>


            <details class="pergunta">

                <summary>
                    Com quanto tempo recebo o valor das inscrições?
                    <span>⌄</span>
                </summary>

                <p>
                   Os valores das inscrições são repassados após a confirmação dos pagamentos, seguindo o prazo definido pela forma de pagamento escolhida e pelas condições da plataforma.
                </p>

            </details>

